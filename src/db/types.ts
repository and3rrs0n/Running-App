// Core domain types. Dates are stored as local ISO date strings "YYYY-MM-DD".

export type ISODate = string;

export type ActivityType = 'run' | 'walk' | 'strength' | 'bike';
export type RunKind = 'easy' | 'long' | 'hills' | 'intervals4x4' | 'hillIntervals';
export type Surface = 'asphalt' | 'gravel' | 'trail' | 'treadmill' | 'other';
export type PainLocation = 'shin' | 'knee' | 'foot' | 'achilles' | 'hip' | 'other';
export type PainTiming = 'during' | 'after' | 'both';
export type StrengthMode = 'home' | 'gym';

export interface PainReport {
  score: number; // 0–10
  locations: PainLocation[];
  timing?: PainTiming;
  description?: string;
}

export interface StrengthExercise {
  name: string;
  sets?: number;
  reps?: string;
  load?: string;
}

/** A completed, registered activity. Never moved or deleted by plan changes. */
export interface Activity {
  id: string;
  type: ActivityType;
  date: ISODate;
  distanceKm?: number;
  durationSec?: number;
  avgHr?: number;
  elevationM?: number;
  surface?: Surface;
  rpe?: number; // 1–10
  pain?: PainReport;
  comment?: string;
  runKind?: RunKind;
  // strength
  strengthMode?: StrengthMode;
  exercises?: StrengthExercise[];
  // bike
  indoor?: boolean;
  avgPower?: number;
  plannedSessionId?: string;
  createdAt: number;
  updatedAt: number;
}

export type SessionStatus = 'planned' | 'completed' | 'skipped';

/** A planned session. Plan-generated sessions belong to a PlanWeek. */
export interface PlannedSession {
  id: string;
  weekId?: string; // PlanWeek id when generated by the plan
  date: ISODate;
  type: ActivityType | 'rest';
  runKind?: RunKind;
  title: string;
  description?: string;
  plannedDistanceKm?: number;
  plannedDurationMin?: number;
  plannedElevationM?: number;
  surfaceHint?: string;
  strengthMode?: StrengthMode;
  status: SessionStatus;
  activityId?: string;
  skipReason?: string;
  source: 'plan' | 'manual';
  userEdited?: boolean; // moved or edited by the user -> never regenerated
  order: number;
  createdAt: number;
  updatedAt: number;
}

export type WeekKind = 'start' | 'build' | 'hold' | 'recovery' | 'reduce' | 'restart' | 'manual';

/** One committed week of the training plan. */
export interface PlanWeek {
  id: string; // = monday ISO date
  monday: ISODate;
  planWeekNo: number; // 1-based count of committed plan weeks
  targetKm: number;
  runCount: number;
  longRunKm?: number;
  kind: WeekKind;
  phase: number;
  reasons: string[];
  locked: boolean; // user override -> engine won't regenerate
  announced?: boolean; // a 'new week' notice has been shown
  createdAt: number;
  updatedAt: number;
}

export type RecoveryStatus = 'good' | 'normal' | 'tired' | 'discomfort' | 'warning';

export interface WeeklyCheckin {
  id: string; // monday ISO of the week assessed
  monday: ISODate;
  status: RecoveryStatus;
  note?: string;
  createdAt: number;
}

export type NoticeKind = 'plan' | 'pain' | 'info' | 'warning';

export interface Notice {
  id: string;
  date: ISODate;
  kind: NoticeKind;
  title: string;
  body: string;
  dismissed: boolean;
  createdAt: number;
}

export type Readiness = 'awaiting' | 'cleared';
export type PlanStatus = 'active' | 'paused';

export interface Settings {
  id: 'main';
  startDate: ISODate;
  readiness: Readiness;
  planStatus: PlanStatus;
  pausedAt?: ISODate;
  startWeeklyKm: number;
  maxRunsPerWeek: number;
  longTermGoalKm: number;
  walkDay: number | null; // 0 = Monday … 6 = Sunday
  walkDistanceKm: number;
  walkElevationM: number;
  strengthDay: number | null;
  restDays: number[];
  preferredRunDays: number[];
  longRunDay: number;
  defaultSurface: Surface;
  easyPaceSecPerKm: number;
  allowHills: boolean;
  allowIntervals: boolean;
  gymMember: boolean;
  gymStartDate?: ISODate;
  lastBackupAt?: number;
  schemaVersion: number;
}
